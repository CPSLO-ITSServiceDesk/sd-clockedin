-- Teams Shifts identity + per-student time off (not academic_term.off_days).

alter table public.student_assistant
  add column if not exists entra_user_id text;

comment on column public.student_assistant.entra_user_id is
  'Microsoft Entra object ID for matching Teams Shifts members; unique when set.';

do $$
begin
  if not exists (
    select 1
    from pg_constraint
    where conname = 'student_assistant_entra_user_id_key'
  ) then
    alter table public.student_assistant
      add constraint student_assistant_entra_user_id_key unique (entra_user_id);
  end if;
end
$$;

create table if not exists public.student_time_off (
  id integer generated by default as identity primary key,
  student_assistant_id integer not null
    references public.student_assistant (id) on delete cascade,
  academic_term_id integer not null
    references public.academic_term (id) on delete cascade,
  starts_at timestamp with time zone not null,
  ends_at timestamp with time zone not null,
  teams_time_off_id text not null,
  time_off_reason text,
  created_at timestamp with time zone not null default now(),
  constraint student_time_off_teams_time_off_id_key unique (teams_time_off_id)
);

comment on table public.student_time_off is
  'Per-student time off copied from Teams Shifts sharedTimeOff for a term.';

create index if not exists student_time_off_academic_term_id_idx
  on public.student_time_off (academic_term_id);

create index if not exists student_time_off_student_assistant_id_idx
  on public.student_time_off (student_assistant_id);

grant select, insert, update, delete on table public.student_time_off
  to anon, authenticated, service_role;

grant usage, select on sequence public.student_time_off_id_seq
  to anon, authenticated, service_role;

