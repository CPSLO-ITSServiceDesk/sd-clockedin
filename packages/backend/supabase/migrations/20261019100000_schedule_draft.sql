-- Work-in-progress term schedule built from availability (Schedule builder at /admin/schedules/new).
-- Nothing here affects schedules or schedule_blocks until the draft is published.

create table if not exists public.schedule_draft (
  id bigint generated by default as identity primary key,
  academic_term_id integer not null
    references public.academic_term (id) on delete cascade,
  status text not null default 'draft',
  -- 1 import · 2 guidelines · 3 review · 4 publish
  step smallint not null default 1,
  source_filename text,
  -- Desk rules (desk hours, minimum on desk, lead every slot, shift length, hour budget, ...).
  rules jsonb not null default '{}'::jsonb,
  -- One entry per student: availability, requested hours, notes and assigned half-hour slots.
  people jsonb not null default '[]'::jsonb,
  -- Imported rows that didn't match a student yet.
  unmatched jsonb not null default '[]'::jsonb,
  change_log jsonb not null default '[]'::jsonb,
  created_at timestamp with time zone not null default now(),
  updated_at timestamp with time zone not null default now(),
  published_at timestamp with time zone,
  constraint schedule_draft_status_check check (status in ('draft', 'published')),
  constraint schedule_draft_step_check check (step between 1 and 4)
);

create index if not exists schedule_draft_term_updated_idx
  on public.schedule_draft (academic_term_id, updated_at desc);

comment on table public.schedule_draft is
  'Term schedule drafts from the schedule builder; publishing writes schedules/schedule_blocks.';

grant select, insert, update, delete on table public.schedule_draft
  to anon, authenticated, service_role;

notify pgrst, 'reload schema';
