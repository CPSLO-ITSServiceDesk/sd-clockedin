-- One row per time the schedule builder sent shifts to Teams Shifts (as drafts),
-- for the whole term schedule or one person. Shown as "Versions" in the builder.

create table if not exists public.teams_schedule_publish (
  id bigint generated by default as identity primary key,
  academic_term_id integer not null
    references public.academic_term (id) on delete cascade,
  -- 'term' (whole draft schedule) or 'person' (one student's change)
  kind text not null,
  student_assistant_id integer
    references public.student_assistant (id) on delete set null,
  from_date date not null,
  to_date date not null,
  created_count integer not null default 0,
  kept_count integer not null default 0,
  removed_count integer not null default 0,
  failed_count integer not null default 0,
  summary text not null default '',
  created_at timestamp with time zone not null default now(),
  constraint teams_schedule_publish_kind_check check (kind in ('term', 'person'))
);

create index if not exists teams_schedule_publish_term_created_idx
  on public.teams_schedule_publish (academic_term_id, created_at desc);

comment on table public.teams_schedule_publish is
  'History of schedule-builder sends to Teams Shifts (drafts; a manager shares them in Teams).';

grant select, insert, update, delete on table public.teams_schedule_publish
  to anon, authenticated, service_role;

